    private void jButtonAñadirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonAñadirActionPerformed

        try {
            int dia = (int) jSpinnerDia.getValue();
            int mes = (int) jSpinnerMes.getValue();
            int anio = (int) jSpinnerAnio.getValue();

            fecha = LocalDate.of(anio, mes, dia);

            if (ControladorFacturas.añadirOActualizarFactura()) {
                jList1.removeAll();
                jList1.setModel(ControladorFacturas.actualizarJList());
            }
        } catch (DateTimeException dte) {
            ControladorFacturas.colocarMensajeError("La fecha introducida no existe.", true);
        }

    }//GEN-LAST:event_jButtonAñadirActionPerformed

    private void jButtonEditarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonEditarActionPerformed
        ControladorFacturas.modoEdicion = true;
        String asuntoFactura = jList1.getSelectedValue().substring(0, jList1.getSelectedValue().indexOf(":"));
        Factura facturaEditar = ControladorFacturas.editarFactura(asuntoFactura);

        if (facturaEditar != null) {
            jTextFieldAsunto.setText(facturaEditar.getAsunto());

            jSpinnerDia.setValue(facturaEditar.getFecha().getDayOfMonth());
            jSpinnerMes.setValue(facturaEditar.getFecha().getMonthValue());
            jSpinnerAnio.setValue(facturaEditar.getFecha().getYear());

            jTextFieldCantidad.setText(Integer.toString(facturaEditar.getCantidad()));

            if (facturaEditar.getTipoFactura() == TipoFactura.EMPRESAS) {
                jComboBoxTipo.setSelectedIndex(0);
            } else {
                jComboBoxTipo.setSelectedIndex(1);
            }

            if (ControladorFacturas.añadirOActualizarFactura()) {
                jList1.removeAll();
                jList1.setModel(ControladorFacturas.actualizarJList());
            }
        }

        asuntoElementoSeleccionado = asuntoFactura;
    }//GEN-LAST:event_jButtonEditarActionPerformed

